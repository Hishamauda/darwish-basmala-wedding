// Sync generated content from assets/js/config.js (single source of truth):
//  - Open Graph / meta block and static text in index.html (for link previews & no-JS readers)
//  - which parts are shown while their data is not confirmed yet (time, map, programme, etiquette)
//  - assets/wedding.ics (calendar file, start/end converted to UTC) — only once the ceremony time is set
// Usage: node tools/sync.mjs
import fs from 'node:fs';
import path from 'node:path';
import vm from 'node:vm';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const sandbox = { window: {} };
vm.runInNewContext(fs.readFileSync(path.join(ROOT, 'assets/js/config.js'), 'utf8'), sandbox);
const C = sandbox.window.WEDDING;
const esc = (s) => String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');
const get = (p) => p.split('.').reduce((o, k) => (o == null ? o : o[k]), C);

function tzOffset(date, tz) {
  const f = new Intl.DateTimeFormat('en-US', { timeZone: tz, hourCycle: 'h23', year: 'numeric', month: '2-digit',
    day: '2-digit', hour: '2-digit', minute: '2-digit', second: '2-digit' });
  const p = Object.fromEntries(f.formatToParts(date).map((x) => [x.type, x.value]));
  return Date.UTC(+p.year, +p.month - 1, +p.day, +p.hour % 24, +p.minute, +p.second) - date.getTime();
}
function zonedToUtc(iso, hhmm, tz) {
  const [y, m, d] = iso.split('-').map(Number), [H, M] = hhmm.split(':').map(Number);
  const guess = Date.UTC(y, m - 1, d, H, M);
  const off = tzOffset(new Date(guess), tz), utc = guess - off, off2 = tzOffset(new Date(utc), tz);
  return new Date(off2 === off ? utc : guess - off2);
}

// ---- index.html
const htmlPath = path.join(ROOT, 'index.html');
let html = fs.readFileSync(htmlPath, 'utf8');
const img = C.site.url + 'assets/img/og-image.jpg';
const name = `${C.couple.groom} ${C.couple.joiner} ${C.couple.bride}`;
const og = `<!-- og:start (generated by tools/sync.mjs from assets/js/config.js) -->
  <title>${esc(C.site.title)}</title>
  <meta name="description" content="${esc(C.site.description)}">
  <link rel="canonical" href="${esc(C.site.url)}">
  <meta property="og:type" content="website">
  <meta property="og:locale" content="ar_AR">
  <meta property="og:site_name" content="${esc(name)}">
  <meta property="og:title" content="${esc(C.site.title)}">
  <meta property="og:description" content="${esc(C.site.description)}">
  <meta property="og:url" content="${esc(C.site.url)}">
  <meta property="og:image" content="${esc(img)}">
  <meta property="og:image:secure_url" content="${esc(img)}">
  <meta property="og:image:type" content="image/jpeg">
  <meta property="og:image:width" content="1200">
  <meta property="og:image:height" content="630">
  <meta property="og:image:alt" content="${esc(name + ' — ' + C.event.dayName + ' ' + C.event.dateLong)}">
  <meta name="twitter:card" content="summary_large_image">
  <meta name="twitter:title" content="${esc(C.site.title)}">
  <meta name="twitter:description" content="${esc(C.site.description)}">
  <meta name="twitter:image" content="${esc(img)}">
  <!-- og:end -->`;
html = html.replace(/<!-- og:start[\s\S]*?<!-- og:end -->/, og);
let n = 0;
html = html.replace(/(<[a-z]+[^>]*\sdata-text="([a-zA-Z.]+)"[^>]*>)([^<]*)(<)/g, (m, open, key, _old, close) => {
  const v = get(key);
  if (typeof v !== 'string') return m;
  n++;
  return open + esc(v).replace(/&quot;/g, '"') + close;
});
// ---- parts that stay hidden until their data is confirmed (app.js applies the same rules at run time)
const slug = new URL(C.site.url).pathname.split('/').filter(Boolean).pop() || 'wedding';
const hasTime = !!(C.event.isoDate && C.event.startTime);
const mapsHref = C.venue.mapsUrl || (C.venue.mapsQuery ? 'https://www.google.com/maps/search/?api=1&query=' + encodeURIComponent(C.venue.mapsQuery) : '');
const hasProgram = !!(C.timeline && C.timeline.length);
const hasEtiquette = !!C.texts.etiquetteText;
function setHidden(marker, hide) {      // add / remove the `hidden` attribute on the opening tag that contains `marker`
  const i = html.indexOf(marker);
  if (i < 0) throw new Error('marker not found: ' + marker);
  const a = html.lastIndexOf('<', i), b = html.indexOf('>', i);
  let tag = html.slice(a, b).replace(/\shidden(?=[\s>]|$)/, '');
  if (hide) tag += ' hidden';
  html = html.slice(0, a) + tag + html.slice(b);
}
setHidden('id="countdown"', !hasTime);
setHidden('id="calendarToggle"', !hasTime);
setHidden('data-text="event.timeLabel"', !C.event.timeLabel);
setHidden('data-time-sep', !C.event.timeLabel);
setHidden('id="mapsLink"', !mapsHref);
setHidden('class="actions"', !mapsHref && !hasTime);
setHidden('id="program"', !hasProgram);
setHidden('data-nav="program"', !hasProgram);
setHidden('id="etiquette"', !hasEtiquette);
html = html.replace(/(id="mapsLink" href=")[^"]*(")/, (m, a, b) => a + esc(mapsHref || '#') + b);
html = html.replace(/(id="countdownNote"[^>]*>)[^<]*(<)/, (m, a, b) =>
  a + (hasTime ? esc(`${C.event.dayName} ${C.event.dateLong} — الساعة ${C.event.timeLabel} بتوقيت غزة`) : '') + b);
html = html.replace(/(id="icsLink" href="assets\/wedding\.ics" download=")[^"]*(")/, (m, a, b) => a + slug + '.ics' + b);
fs.writeFileSync(htmlPath, html);

// ---- calendar file: never with an unconfirmed time
const icsPath = path.join(ROOT, 'assets/wedding.ics');
if (!hasTime) {
  if (fs.existsSync(icsPath)) fs.unlinkSync(icsPath);
  console.log(`synced: ${n} text nodes, OG block; no ceremony time yet → countdown, calendar and wedding.ics left out` +
    `${hasProgram ? '' : ', programme hidden'}${mapsHref ? '' : ', map button hidden'}${hasEtiquette ? '' : ', etiquette hidden'}`);
  process.exit(0);
}
const start = zonedToUtc(C.event.isoDate, C.event.startTime, C.event.timeZone);
const end = zonedToUtc(C.event.isoDate, C.event.endTime || C.event.startTime, C.event.timeZone);
const stamp = (d) => d.toISOString().replace(/[-:]/g, '').replace(/\.\d{3}/, '');
const fold = (line) => { // RFC 5545: fold at 75 octets
  const out = []; let buf = Buffer.from(line, 'utf8');
  while (buf.length > 75) { let cut = 75; while ((buf[cut] & 0xc0) === 0x80) cut--; out.push(buf.slice(0, cut).toString('utf8')); buf = Buffer.concat([Buffer.from(' '), buf.slice(cut)]); }
  out.push(buf.toString('utf8')); return out.join('\r\n');
};
const icsText = (s) => String(s).replace(/\\/g, '\\\\').replace(/;/g, '\;').replace(/,/g, '\\,').replace(/\n/g, '\\n');
const ics = ['BEGIN:VCALENDAR', 'VERSION:2.0', `PRODID:-//${slug}//invitation//AR`, 'CALSCALE:GREGORIAN', 'METHOD:PUBLISH',
  'BEGIN:VEVENT', `UID:${slug}-${C.event.isoDate}@hishamauda.github.io`, `DTSTAMP:${stamp(new Date())}`,
  `DTSTART:${stamp(start)}`, `DTEND:${stamp(end)}`,
  `SUMMARY:${icsText('زفاف ' + name)}`, `LOCATION:${icsText(C.venue.name + '، ' + C.venue.address)}`,
  `DESCRIPTION:${icsText(C.texts.shareText + '\n' + C.site.url)}`, `URL:${C.site.url}`,
  'BEGIN:VALARM', 'TRIGGER:-P1D', 'ACTION:DISPLAY', `DESCRIPTION:${icsText('غدًا زفاف ' + name)}`, 'END:VALARM',
  'END:VEVENT', 'END:VCALENDAR'].map(fold).join('\r\n') + '\r\n';
fs.writeFileSync(icsPath, ics);
console.log(`synced: ${n} text nodes, OG block, wedding.ics (start ${start.toISOString()}, end ${end.toISOString()})`);
